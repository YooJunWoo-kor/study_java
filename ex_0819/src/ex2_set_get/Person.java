package ex2_set_get;

public class Person {
    
    private String gender;

    public void setGender(String g){
        gender = g;
    }

    public String getGender(){
        return gender;
    }
    String name;

    public void setName(String s){
        name = s;
    }

    public String getName(){
        return name;
    }

    int age;

    public void setAge(int n){
        age = n;
    }

    public int getAge(){
        return age;
    }
    
}
